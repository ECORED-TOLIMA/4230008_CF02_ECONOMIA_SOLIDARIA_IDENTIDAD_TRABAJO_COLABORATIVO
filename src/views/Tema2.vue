                p.mb-0 La encuesta es una técnica que recoge información estandarizada mediante preguntas claras, aplicadas a varias personas de la organización. Permite comparar respuestas, identificar tendencias y reconocer necesidades comunes sobre participación, satisfacción, formación o servicios. En una cooperativa cafetera del Tolima, por ejemplo, puede aplicarse a los asociados para conocer horarios de capacitación, dificultades de transporte, acceso a insumos y temas prioritarios para mejorar la comercialización conjunta y tomar decisiones con datos verificables en beneficio de las familias vinculadas al proceso.
            .row(titulo="Entrevista")
              .col-12.mb-0.mb-md-0
                p.mb-0 La entrevista es una técnica cualitativa que permite profundizar en experiencias, opiniones y conocimientos de actores clave mediante una conversación guiada. Ayuda a comprender causas, significados y expectativas que no siempre aparecen en una encuesta. En una asociación de mujeres rurales de Santander, por ejemplo, puede realizarse con lideresas, compradoras y funcionarios locales para identificar barreras de mercado, apoyos disponibles, necesidades de formación y oportunidades de articulación institucional para fortalecer la producción comunitaria organizada en el territorio rural colombiano actual.
            .row(titulo="Observación directa")
              .col-12.mb-0.mb-md-0
